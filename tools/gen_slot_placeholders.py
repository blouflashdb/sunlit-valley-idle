def render(grid):
    if len(grid) != 16 or any(len(row) != 16 for row in grid):
        raise ValueError("sprite grids must be 16x16")
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch == "#":
                img.putpixel((x, y), FILL)
            elif ch == "+":
                img.putpixel((x, y), EDGE)
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", help="also write an enlarged preview sheet on a slot-colored background")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    images = {}
    for name, grid in SPRITES.items():
        images[name] = render(grid)
        images[name].save(OUT / f"{name}.png", optimize=True)
        print(f"wrote {OUT.relative_to(ROOT) / (name + '.png')}")
    if args.preview:
        scale = 8
        sheet = Image.new("RGBA", (len(images) * 18 * scale, 18 * scale), (198, 198, 198, 255))
        for i, img in enumerate(images.values()):
            slot = Image.new("RGBA", (16, 16), (139, 139, 139, 255))
            slot.alpha_composite(img)
            sheet.paste(slot.resize((16 * scale, 16 * scale), Image.NEAREST), ((i * 18 + 1) * scale, scale))
        sheet.save(args.preview)


if __name__ == "__main__":
    main()
