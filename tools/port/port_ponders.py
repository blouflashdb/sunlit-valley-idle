#!/usr/bin/env python3
"""Lists the blocks, block states and items that the Ponder scenes in kubejs/client_scripts/ponders use.

The scenes run on the client only, so the server boot test cannot play them. Instead ponderBlocksTest.js checks
that every block, block state property and item they name exists on 1.21.1. Writes
tools/port/kubejs_tests/ponderBlocksData.js. Run from the repository root: python3 tools/port/port_ponders.py
"""
import json
import pathlib
import re

PONDERS = pathlib.Path("kubejs/client_scripts/ponders")
TEST_DATA = pathlib.Path("tools/port/kubejs_tests/ponderBlocksData.js")
TAGS = {"society:cooking_brewing"}  # the Ponder tag of ponderTags.js


def main():
    states, blocks, items = set(), set(), set()
    for path in sorted(PONDERS.rglob("*.js")):
        text = path.read_text()
        for match in re.finditer(r'Block\.id\("([^"]+)"\)((?:\.with\([^)]*\))*)', text):
            props = re.findall(r'\.with\("([^"]+)",\s*"?([^")]+)"?\)', match.group(2))
            for name, value in props:
                states.add((match.group(1), name, value.strip()))
            blocks.add(match.group(1))
        for match in re.finditer(r'(?:setBlocks|replaceBlocks)\((?:\[[^\]]*\]|[^,\[]+),\s*"([^"]+)"', text):
            blocks.add(match.group(1))
        # every other id (items in hands, item entities) must be an item
        for match in re.finditer(r"['\"]([a-z_]+:[a-z_/]+)['\"]", text):
            if match.group(1) not in blocks and match.group(1) not in TAGS:
                items.add(match.group(1))
    TEST_DATA.write_text(
        "// Generated by tools/port/port_ponders.py: what the Ponder scenes (kubejs/client_scripts/ponders) use.\n"
        f"const ponderBlocks = {json.dumps(sorted(blocks))};\n"
        f"const ponderStates = {json.dumps(sorted(list(s) for s in states))};\n"
        f"const ponderItems = {json.dumps(sorted(items))};\n"
    )
    print(f"{len(blocks)} blocks, {len(states)} block state values, {len(items)} items")


if __name__ == "__main__":
    main()
